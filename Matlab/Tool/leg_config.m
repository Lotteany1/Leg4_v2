%
%! I_leg 口径冲突: 按上表口径 (绕 pitch 轴) 平行轴定理要求 I_leg ≥ m_leg·l_d²,
%! 但 m_leg=1.855 kg 时 19/19 行违反 (I_leg − m_leg·l_d² ∈ [−4.66e-2, −9.0e-3]
%! kg·m², 反推等效质量仅 0.55~1.19 kg); m_leg / l_d / I_leg 三者至少一项口径有误,
%! 待作者裁定, 在裁定前不要改表值 (一改会自动触发 s03 几何缓存重算)。
%
%   See also: Leg_Comp, Leg_SpringF, Leg_RollComp, Leg_CoriolisComp,
