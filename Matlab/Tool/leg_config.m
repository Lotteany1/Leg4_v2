% ==================== 整机与硬件 ====================
% 修改整车质量时只改 m_total；分项质量沿用现有标定，支撑质量和机身质量自动派生。
% 修改后重跑 build_leg_tool 和 build_leglen_mpc；平衡模型的数据表有独立生成入口。
% 先计算局部标量，再组装 par，避免 MATLAB Coder 在结构体读后新增字段。
m_total   = 12.67891464965;                    % 整车含电池、两腿和两轮的实测总质量 [kg]
m_leg     = 1.306200443681;                   % 单腿质量（轮以上部分） [kg]
m_wheel   = 1.240464069458;                    % 单轮与轮毂电机质量 [kg]
m_support = m_total - 2 * m_wheel;    % 轮以上支撑质量 [kg]
m_body    = m_support - 2 * m_leg;    % 不含两腿和两轮的机身质量 [kg]

par.g           = 9.81;      % 重力加速度                              [m/s²]
par.m_total     = m_total;   % 整车总质量                              [kg]
par.m_leg       = m_leg;     % 单腿质量 (轮以上部分)                    [kg]
par.m_body      = m_body;    % 机身质量，不含腿轮                       [kg]
