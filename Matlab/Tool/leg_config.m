knee_at_max = acos((l1^2 + l2^2 - leg_len_max^2)/(2*l1*l2));
pin_angle_at_max = acos((qh^2 + ph^2 - pin_at_max^2)/(2*qh*ph));

par.SprF        = 400.0;              % 最短销距处的轴向推力 [N]，与当前固件标定一致
par.Spr_pin_max = 0.220;              % 规格图全伸销距 [m]
par.Spr_pin_min = 0.150;              % 规格图全伸销距减 70 mm 行程 [m]
par.Spr_phi     = knee_at_max - pin_angle_at_max; % 伸腿时销距增加的装配分支 [rad]
par.Spr_s1      = qh;
par.Spr_s2      = ph;
par.Spr_l1      = l1;
par.Spr_l2      = l2;
par.Spr_len_min = 0.05;               % 腿长计算域下限 [m]
