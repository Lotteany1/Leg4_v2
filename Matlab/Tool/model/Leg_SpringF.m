function Fs = Leg_SpringF(L0,ang)
%#codegen
% 实车试调：按原辨识的腿向补偿力缩放，左右共用，伸腿为正 [N]。
% 本轮在 130–190 mm 增加 2 N，120–130 和 190–200 mm 线性过渡。
nodes = cast([
    0.12, 65.30;
    0.13, 67.30;
    0.17, 67.30;
    0.18, 77.55;
    0.19, 95.83;
    0.20, 110.89;
    0.21, 112.49;
    0.22, 112.65;
    0.23, 112.76;
    0.24, 113.61;
    0.25, 120.34;
    0.26, 122.21;
    0.27, 124.11;
    0.28, 126.03;
    0.29, 128.89;
    0.30, 135.06;
    0.31, 139.68;
    0.32, 146.86;
    0.33, 152.47;
    0.34, 158.15;
], 'like', L0);
Fs = nodes(end,2);
if L0 <= nodes(1,1)
    Fs = nodes(1,2);
    return;
end
for k = 2:size(nodes,1)
    if L0 <= nodes(k,1)
        ratio = (L0-nodes(k-1,1))/(nodes(k,1)-nodes(k-1,1));
        Fs = nodes(k-1,2)+ratio*(nodes(k,2)-nodes(k-1,2));
        return;
    end
end
end
